export function distanceKm(a, b) {
 const rad = Math.PI / 180;
 const dlat = (b.latitude-a.latitude)*rad, dlon=(b.longitude-a.longitude)*rad;
 const h=Math.sin(dlat/2)**2+Math.cos(a.latitude*rad)*Math.cos(b.latitude*rad)*Math.sin(dlon/2)**2;
 return 6371*2*Math.asin(Math.sqrt(Math.min(1,h)));
}
export function regionFor(place) {
 return REGIONS.map(region=>({region,distance:distanceKm(place,region)}))
  .filter(x=>x.distance<=x.region.radiusKm).sort((a,b)=>a.distance-b.distance)[0] ?? null;
}
export function slotFor(region, now) {
 const period=180*60000, offset=region.offsetMinutes*60000;
 return Math.floor((now-offset)/period)*period+offset;
}
